import argparse

import numpy as np
import sklearn.datasets
import sklearn.metrics
import sklearn.model_selection

parser = argparse.ArgumentParser()
# These arguments will be set appropriately by ReCodEx, even if you change them.
parser.add_argument("--batch_size", default=10, type=int, help="Batch size")
parser.add_argument("--classes", default=10, type=int, help="Number of classes to use")
parser.add_argument("--epochs", default=10, type=int, help="Number of SGD training epochs")
parser.add_argument("--learning_rate", default=0.01, type=float, help="Learning rate")
parser.add_argument("--recodex", default=False, action="store_true", help="Running in ReCodEx")
parser.add_argument("--seed", default=244, type=int, help="Random seed")
parser.add_argument("--test_size", default=797, type=lambda x: int(x) if x.isdigit() else float(x), help="Test size")
# If you add more arguments, ReCodEx will keep them with your default values.


def get_batches( x, y, batch_size, permutation = None):
    """
    Generator of minibatches from data in numpy arrays
    """
    if (permutation is not None):
        x = x[permutation]
        y = y[permutation]

    for start_idx in range(0, x.shape[0], batch_size):
        end_idx = start_idx + batch_size
        x_batch = x[start_idx : end_idx]
        y_batch = y[start_idx : end_idx]

        yield x_batch, y_batch

def evaluate_nn( data, target, weights ):
    prediction = data @ weights
    max_prediction = np.max(prediction, axis=1, keepdims=True)

    # to prevent overflow in softmax
    prediction = prediction - max_prediction
    probability = np.exp(prediction) / np.sum( np.exp(prediction), axis=1, keepdims=True )

    classification = np.argmax(probability, axis=1)
    accuracy = np.mean( classification == target )

    loss = - np.mean( np.log(probability[np.arange(target.shape[0]), target]) )
    return accuracy, loss


def main(args: argparse.Namespace) -> tuple[np.ndarray, list[tuple[float, float]]]:
    # Create a random generator with a given seed.
    generator = np.random.RandomState(args.seed)

    # Load the digits dataset.
    data, target = sklearn.datasets.load_digits(n_class=args.classes, return_X_y=True)

    # Append a constant feature with value 1 to the end of all input data.
    # Then we do not need to explicitly represent bias - it becomes the last weight.
    data = np.pad(data, [(0, 0), (0, 1)], constant_values=1)

    # Split the dataset into a train set and a test set.
    # Use `sklearn.model_selection.train_test_split` method call, passing
    # arguments `test_size=args.test_size, random_state=args.seed`.
    train_data, test_data, train_target, test_target = sklearn.model_selection.train_test_split(
        data, target, test_size=args.test_size, random_state=args.seed)

    # Generate initial model weights.
    weights = generator.uniform(size=[train_data.shape[1], args.classes], low=-0.1, high=0.1)

    for epoch in range(args.epochs):
        permutation = generator.permutation(train_data.shape[0])

        # TODO: Process the data in the order of `permutation`. For every
        # `args.batch_size` of them, average their gradient, and update the weights.
        # You can assume that `args.batch_size` exactly divides `train_data.shape[0]`.
        #
        # Note that you need to be careful when computing softmax because the exponentiation
        # in softmax can easily overflow. To avoid it, you should use the fact that
        # $softmax(z) = softmax(z + any_constant)$ and compute $softmax(z) = softmax(z - maximum_of_z)$.
        # That way we only exponentiate non-positive values, and overflow does not occur.

        for train_data_batch, train_target_batch in get_batches(train_data, train_target, args.batch_size, permutation= permutation):
            # predict values based on current weights and data batch
            predictions = train_data_batch @ weights

            # modify prediction to prevent overflow in softmax
            max_predictions = np.max(predictions, axis=1, keepdims=True)
            predictions = predictions - max_predictions

            # compute probabilities of all classifications using softmax
            probabilities = np.exp(predictions) / np.sum( np.exp( predictions ), axis=1, keepdims=True )

            # gradient computation of estimated loss function (no need to compute the loss function)
            onehot_train_target_batch = np.identity(args.classes)[ train_target_batch ]
            prediction_dif = probabilities - onehot_train_target_batch
            gradient = train_data_batch.T @ prediction_dif / train_data_batch.shape[0]

            # apply the gradient
            weights = weights - gradient * args.learning_rate
        

        # TODO: After the SGD epoch, measure the average loss and accuracy for both the
        # train test and the test set. The loss is the average MLE loss (i.e., the
        # negative log-likelihood, or cross-entropy loss, or KL loss) per example.

        # compute loss for train and test data
        train_accuracy, train_loss = evaluate_nn(train_data, train_target, weights)
        test_accuracy, test_loss = evaluate_nn(test_data, test_target, weights)

        print("After epoch {}: train loss {:.4f} acc {:.1f}%, test loss {:.4f} acc {:.1f}%".format(
            epoch + 1, train_loss, 100 * train_accuracy, test_loss, 100 * test_accuracy))

    return weights, [(train_loss, 100 * train_accuracy), (test_loss, 100 * test_accuracy)]


